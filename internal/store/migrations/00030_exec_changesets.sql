-- Phase 5 (task 5.1): changesets, stored by the executor only.
--
-- A changeset is append-only like a change session (security.md 5.4, D1):
-- the changeset row, one row per revision (a draft edited is a new
-- revision; the content is the executor's canonical encoding of
-- changeset.Content with its SHA-256) and its events (dry-run, approvals,
-- run, discard). Every row carries the executor's HMAC (domain
-- nms/changeset/v1); the state is the newest revision plus the events, read
-- back and verified by the executor, never decided from execpub.
-- The content is bounded below registry.MaxMessage (1 MiB per message):
-- a revision must come back through the executor's bounded connections.
-- Foreign keys stay inside exec (none into core).

CREATE TABLE exec.changeset (
    id              uuid        PRIMARY KEY,
    author          bigint      NOT NULL CHECK (author > 0),
    author_username text        NOT NULL CHECK (octet_length(author_username) BETWEEN 1 AND 256),
    kind            text        NOT NULL CHECK (kind IN ('lines', 'restore')),
    created_at      timestamptz NOT NULL,
    mac             bytea       NOT NULL CHECK (octet_length(mac) = 32)
);
CREATE INDEX changeset_created_at_idx ON exec.changeset (created_at DESC);

CREATE TABLE exec.changeset_revision (
    changeset_id   uuid        NOT NULL REFERENCES exec.changeset (id),
    rev            int         NOT NULL CHECK (rev BETWEEN 1 AND 1000),
    created_at     timestamptz NOT NULL,
    content        bytea       NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 960 * 1024),
    content_sha256 bytea       NOT NULL CHECK (octet_length(content_sha256) = 32),
    mac            bytea       NOT NULL CHECK (octet_length(mac) = 32),
    PRIMARY KEY (changeset_id, rev)
);

CREATE TABLE exec.changeset_event (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    changeset_id uuid        NOT NULL,
    rev          int         NOT NULL,
    at           timestamptz NOT NULL,
    kind         text        NOT NULL CHECK (kind ~ '^[a-z0-9_.-]{1,64}$'),
    device_id    bigint      NULL CHECK (device_id > 0),
    session_id   uuid        NULL,
    payload      jsonb       NOT NULL
        CHECK (jsonb_typeof(payload) = 'object' AND octet_length(payload::text) <= 65536),
    mac          bytea       NOT NULL CHECK (octet_length(mac) = 32),
    FOREIGN KEY (changeset_id, rev) REFERENCES exec.changeset_revision (changeset_id, rev)
);
CREATE INDEX changeset_event_changeset_idx ON exec.changeset_event (changeset_id, id);

CREATE TRIGGER changeset_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON exec.changeset
    FOR EACH STATEMENT EXECUTE FUNCTION exec.reject_modification();
CREATE TRIGGER changeset_revision_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON exec.changeset_revision
    FOR EACH STATEMENT EXECUTE FUNCTION exec.reject_modification();
CREATE TRIGGER changeset_event_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON exec.changeset_event
    FOR EACH STATEMENT EXECUTE FUNCTION exec.reject_modification();

-- The panel's list of changesets (metadata only: never lines or configurations).
CREATE TABLE execpub.changeset_summary (
    changeset_id     uuid        PRIMARY KEY,
    author_id        bigint      NOT NULL CHECK (author_id > 0),
    kind             text        NOT NULL CHECK (kind IN ('lines', 'restore')),
    title            text        NOT NULL CHECK (octet_length(title) BETWEEN 1 AND 480 AND char_length(title) <= 120),
    status           text        NOT NULL CHECK (status IN ('draft', 'dry_run_ok', 'dry_run_failed', 'approved', 'running',
                                                            'done', 'rolled_back', 'rollback_failed', 'interrupted', 'discarded')),
    device_count     int         NOT NULL CHECK (device_count BETWEEN 0 AND 200),
    device_ids       bigint[]    NOT NULL CHECK (cardinality(device_ids) <= 200
                                                 AND (cardinality(device_ids) = 0 OR array_ndims(device_ids) = 1)
                                                 AND array_position(device_ids, NULL) IS NULL),
    created_at       timestamptz NOT NULL,
    updated_at       timestamptz NOT NULL,
    failed_device_id bigint      NULL CHECK (failed_device_id > 0)
);
CREATE INDEX changeset_summary_updated_idx ON execpub.changeset_summary (updated_at DESC);

REVOKE ALL ON exec.changeset, exec.changeset_revision, exec.changeset_event, execpub.changeset_summary FROM PUBLIC;
REVOKE ALL ON SEQUENCE exec.changeset_event_id_seq FROM PUBLIC;
GRANT SELECT, INSERT ON exec.changeset, exec.changeset_revision, exec.changeset_event TO nms_executor;
GRANT USAGE ON SEQUENCE exec.changeset_event_id_seq TO nms_executor;
GRANT SELECT, INSERT, UPDATE, DELETE ON execpub.changeset_summary TO nms_executor;
GRANT SELECT ON execpub.changeset_summary TO nms_api;

