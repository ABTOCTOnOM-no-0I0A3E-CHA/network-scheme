package registry

import (
	"slices"
	"strings"
)

/*
kind is how a column is scanned (binary protocol, into Go values) and
encoded. The MAC covers the Go values the executor decides on, never a text
rendered by the server, so no server-side function or cast takes part.
*/
type kind int

const (
	kInt8  kind = iota /* bigint */
	kInt4              /* integer */
	kBool              /* boolean */
	kText              /* text */
	kBytes             /* bytea */
	kTime              /* timestamptz, microseconds */
	kInet              /* inet, a single host address */
	kJSON              /* jsonb, canonicalised in Go */
)

/* sqlType is format_type() of each kind, for the catalog check. */
var sqlType = map[kind]string{
	kInt8: "bigint", kInt4: "integer", kBool: "boolean", kText: "text", kBytes: "bytea",
	kTime: "timestamp with time zone", kInet: "inet", kJSON: "jsonb",
}

type column struct {
	name string
	kind kind
	null bool   /* NULL allowed */
	def  string /* pg_get_expr of the DEFAULT, "" for none; "identity" for GENERATED BY DEFAULT AS IDENTITY */
}

/* table is one registry table: its key, the MACed content and the version column. */
type table struct {
	name    string
	pk      []column
	content []column
	version string
}

const (
	counterTable = "registry_counter"
	stateTable   = "exec_state"
)

/*
tables is the whole registry. Every column of each table except mac is
either key, content or version, and the catalog check (catalog.go) insists
the database has exactly these columns, types and defaults. The
append-only tables (sessions, recordings, audit) are not registry: they are
never updated and carry their own MACs (4c).
*/
var tables = []table{
	{name: counterTable, pk: []column{{"singleton", kBool, false, "true"}}, version: "seq"},
	{name: "write_device", pk: []column{{"device_id", kInt8, false, ""}}, content: []column{
		{"address", kInet, false, ""}, {"port", kInt4, false, "22"}, {"protocol", kText, false, "'ssh'::text"},
		{"write_group", kText, false, ""}, {"write_driver", kText, false, ""},
		{"hostkey_algo", kText, true, ""}, {"hostkey_fp", kText, true, ""},
		{"allow_ssh_rsa_sha1", kBool, false, "false"}, {"writes_enabled", kBool, false, "false"},
		{"backup_via_executor", kBool, false, "false"},
	}, version: "version"},
	{name: "write_grant", pk: []column{{"user_id", kInt8, false, ""}, {"kind", kText, false, ""}, {"write_group", kText, true, ""}},
		content: []column{{"username_snapshot", kText, false, ""}}, version: "version"},
	{name: "change_totp", pk: []column{{"user_id", kInt8, false, ""}}, content: []column{
		{"username_snapshot", kText, false, ""}, {"ciphertext", kBytes, false, ""}, {"key_version", kInt4, false, ""},
		{"last_step", kInt8, false, "0"}, {"failures", kInt4, false, "0"}, {"lock_until", kTime, true, ""},
		{"lock_count", kInt4, false, "0"},
	}, version: "version"},
	{name: stateTable, pk: []column{{"singleton", kBool, false, "true"}}, content: []column{
		{"freeze", kBool, false, ""}, {"freeze_reason", kText, true, ""}, {"global_fail_window", kJSON, false, "'[]'::jsonb"},
	}, version: "version"},
	{name: "model_profile", pk: []column{{"id", kInt8, false, "identity"}}, content: []column{
		{"write_driver", kText, false, ""}, {"model_re", kText, false, ""}, {"firmware_re", kText, false, ""},
		{"strategies", kJSON, false, "'{}'::jsonb"}, {"note", kText, false, ""},
	}, version: "version"},
	{name: "write_credential", pk: []column{{"device_id", kInt8, false, ""}}, content: []column{
		{"kind", kText, false, ""}, {"ciphertext", kBytes, false, ""}, {"created_at", kTime, false, ""},
		{"nonce", kBytes, false, ""},
	}, version: "version"},
}

func lookup(name string) *table {
	for i := range tables {
		if tables[i].name == name {
			return &tables[i]
		}
	}
	return nil
}

func (t *table) columns() []column { return append(append([]column(nil), t.pk...), t.content...) }

func quote(name string) string { return `"` + name + `"` }

func (t *table) qname() string { return "exec." + quote(t.name) }

/* selectSQL reads key, content, version and mac: plain column references, no function, operator or cast. */
func (t *table) selectSQL() string {
	var names []string
	for _, c := range t.columns() {
		names = append(names, quote(c.name))
	}
	names = append(names, quote(t.version), "mac")
	return "SELECT " + strings.Join(names, ", ") + " FROM " + t.qname()
}

/* upsertSQL writes one full row: every column explicitly, so no DEFAULT is ever used. */
func (t *table) upsertSQL() string {
	var names, params, pks, set []string
	for i, c := range append(t.columns(), column{name: t.version}, column{name: "mac"}) {
		names = append(names, quote(c.name))
		params = append(params, "$"+itoa(i+1))
	}
	for _, c := range t.pk {
		pks = append(pks, quote(c.name))
	}
	for _, c := range append(slices.Clone(t.content), column{name: t.version}, column{name: "mac"}) {
		set = append(set, quote(c.name)+" = EXCLUDED."+quote(c.name))
	}
	return "INSERT INTO " + t.qname() + " (" + strings.Join(names, ", ") + ") VALUES (" + strings.Join(params, ", ") +
		") ON CONFLICT (" + strings.Join(pks, ", ") + ") DO UPDATE SET " + strings.Join(set, ", ")
}

/* deleteSQL removes one row by key (a NULL key part matches NULL). */
func (t *table) deleteSQL() string {
	var conds []string
	for i, c := range t.pk {
		conds = append(conds, quote(c.name)+" IS NOT DISTINCT FROM $"+itoa(i+1))
	}
	return "DELETE FROM " + t.qname() + " WHERE " + strings.Join(conds, " AND ")
}

/* fingerprint is what the catalog must say about the table's columns (catalog.go builds the same text). */
func (t *table) fingerprint() string {
	var parts []string
	for _, c := range append(t.columns(), column{name: t.version, kind: kInt8}, column{name: "mac", kind: kBytes}) {
		ident, def := "", c.def
		if def == "identity" {
			ident, def = "d", ""
		}
		coll := ""
		if c.kind == kText {
			coll = "default"
		}
		parts = append(parts, c.name+" "+sqlType[c.kind]+" "+ident+" "+def+" "+coll)
	}
	slices.Sort(parts)
	return strings.Join(parts, ",")
}
